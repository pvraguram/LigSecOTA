"""
ONE module for every cryptographic operation, in two suites:

  SUITE "v1"  -- faithful to the paper. AES-CBC + HMAC-MD5, Encrypt-and-MAC,
                 ONE key used for both the cipher and the MAC, RSA key
                 transport for the handshake. Flaws are intentional; see
                 Handbook Chapter 18 (F2, F4, F5, F9, F10).

  SUITE "v2"  -- the improved design from Handbook Chapter 17. AES-256-GCM,
                 HKDF-derived, domain-separated keys, signed ephemeral ECDH
                 for forward secrecy, Ed25519 signatures.

Keeping both in one file means a scenario can flip `SUITE` and nothing
else changes -- the comparison stays controlled (Handbook 13.3).
"""
import hashlib
import hmac
import os

from cryptography.hazmat.primitives import hashes, padding as sympad
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, padding, rsa
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

from common.wire import ProtocolError


class IntegrityError(ProtocolError):
    pass


class PaddingOracleError(ProtocolError):
    """Raised SEPARATELY from IntegrityError in v1 on purpose, so the
    attacker harness (attack/scenarios.py, A5) can demonstrate that the
    two failure modes are distinguishable -- the padding-oracle flaw,
    Handbook 6.2 / 18 F4."""
    pass


# --------------------------------------------------------------- key sizes
# The paper's G_1 (RSA-512/DSA-512) cannot even be generated by a current
# cryptography library (see Handbook 5.5 / 6.6) -- itself a small piece of
# evidence that it is not a deployable security level. We keep the paper's
# naming but move the floor up to the smallest size OpenSSL will still
# produce, and label it clearly.
RSA_GROUPS = {
    "G1": 1024,   # paper specifies 512; library-enforced floor. NOT SAFE.
    "G2": 2048,
    "G3": 3072,
}


# =================================================================== v1
def v1_keypair(bits=2048):
    priv = rsa.generate_private_key(public_exponent=65537, key_size=bits)
    return priv, priv.public_key()


def v1_rsa_wrap(pub, plaintext: bytes) -> bytes:
    """RSA-OAEP key transport. No forward secrecy: a future compromise of
    the matching private key decrypts every session ever wrapped under it
    (Handbook 6.7 / 18 F5)."""
    return pub.encrypt(
        plaintext,
        padding.OAEP(mgf=padding.MGF1(hashes.SHA256()),
                     algorithm=hashes.SHA256(), label=None))


def v1_rsa_unwrap(priv, ct: bytes) -> bytes:
    return priv.decrypt(
        ct, padding.OAEP(mgf=padding.MGF1(hashes.SHA256()),
                          algorithm=hashes.SHA256(), label=None))


def v1_sign(priv, data: bytes) -> bytes:
    return priv.sign(data, padding.PKCS1v15(), hashes.SHA256())


def v1_verify(pub, sig: bytes, data: bytes):
    pub.verify(sig, data, padding.PKCS1v15(), hashes.SHA256())


def v1_protect(key: bytes, plaintext: bytes):
    """AES-CBC + HMAC-MD5. Encrypt-and-MAC: the tag covers PLAINTEXT, and
    is computed with the SAME key as the cipher -- exactly as specified
    (Section VI-C / Fig. 8 of the paper). Handbook 6.3, 18 F4."""
    iv = os.urandom(16)
    padder = sympad.PKCS7(128).padder()
    body = padder.update(plaintext) + padder.finalize()
    enc = Cipher(algorithms.AES(key), modes.CBC(iv)).encryptor()
    ct = enc.update(body) + enc.finalize()
    tag = hmac.new(key, plaintext, hashlib.md5).digest()
    return iv + ct, tag


def v1_unprotect(key: bytes, blob: bytes, tag: bytes) -> bytes:
    """Decrypt-then-verify, in that order, exactly as the paper's message
    flow implies (decrypt to get the header before anything else happens).
    This ordering is what makes a padding oracle possible: a malformed
    ciphertext fails at the PKCS7-unpad step, before the MAC is ever
    checked, and raises a DIFFERENT exception than a bad-MAC failure."""
    iv, ct = blob[:16], blob[16:]
    dec = Cipher(algorithms.AES(key), modes.CBC(iv)).decryptor()
    padded = dec.update(ct) + dec.finalize()
    try:
        unpadder = sympad.PKCS7(128).unpadder()
        pt = unpadder.update(padded) + unpadder.finalize()
    except ValueError as e:
        # distinguishable from IntegrityError below -- the flaw itself
        raise PaddingOracleError("bad padding") from e
    expected = hmac.new(key, pt, hashlib.md5).digest()
    if not hmac.compare_digest(expected, tag):
        raise IntegrityError("bad tag")
    return pt


# =================================================================== v2
def v2_keypair():
    priv = ed25519.Ed25519PrivateKey.generate()
    return priv, priv.public_key()


def v2_sign(priv, data: bytes) -> bytes:
    return priv.sign(data)


def v2_verify(pub, sig: bytes, data: bytes):
    pub.verify(sig, data)   # raises InvalidSignature on failure


def v2_ephemeral():
    priv = ec.generate_private_key(ec.SECP256R1())
    return priv, priv.public_key()


def v2_ecdh(my_eph_priv, peer_eph_pub) -> bytes:
    return my_eph_priv.exchange(ec.ECDH(), peer_eph_pub)


def hkdf(master: bytes, label: bytes, n: int = 32) -> bytes:
    return HKDF(algorithm=hashes.SHA256(), length=n, salt=None,
                info=label).derive(master)


def v2_protect(master_key: bytes, plaintext: bytes, aad: bytes, counter: int):
    """AES-256-GCM with an HKDF-derived, domain-separated encryption key
    and a per-message nonce built from a counter (safe because v1 already
    guarantees a fresh master_key per update -- Handbook 6.4). `aad` binds
    protocol version, message type, sender, recipient, session id and the
    expected header into the tag without encrypting them (Handbook 9.2)."""
    k_enc = hkdf(master_key, b"ligsecota/v2/pkg-encryption")
    nonce = counter.to_bytes(12, "big")
    ct = AESGCM(k_enc).encrypt(nonce, plaintext, aad)
    return ct, nonce


def v2_unprotect(master_key: bytes, ct: bytes, aad: bytes, nonce: bytes) -> bytes:
    k_enc = hkdf(master_key, b"ligsecota/v2/pkg-encryption")
    try:
        return AESGCM(k_enc).decrypt(nonce, ct, aad)
    except Exception as e:   # InvalidTag and friends -- ONE uniform failure
        raise IntegrityError("bad tag") from e


class MonotonicCounter:
    """Stand-in for a fuse-backed anti-rollback counter (Handbook 7.5,
    17.3). v2 refuses to install any sec_version below the high-water
    mark, permanently -- not just outside a timestamp window."""

    def __init__(self):
        self._v = {}

    def read(self, ecu_id):
        return self._v.get(ecu_id, -1)

    def bump(self, ecu_id, sec_version):
        self._v[ecu_id] = max(self._v.get(ecu_id, -1), sec_version)
